"""Phase 1: run every pre-registered strategy, select on IS, judge on OOS.

    python run_research.py            # real data (needs internet)
    python run_research.py --refresh  # re-download data
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from edge import data, null
from edge.backtest import metrics
from edge.stats import deflated_sharpe
from edge.strategies import MARKETS

IS_END = pd.Timestamp("2022-12-31")
TBILL = 0.04
REPORTS = Path(__file__).resolve().parent / "reports"
REPORTS.mkdir(exist_ok=True)


def evaluate(panels: dict) -> tuple[pd.DataFrame, dict]:
    rows, streams = [], {}
    for mname, mod in MARKETS.items():
        panel = panels[mname]
        for fam, (fn, grid) in mod.FAMILIES.items():
            for params in grid:
                res = fn(panel, **params)
                r = res.returns[res.exposure.cumsum() > 0]  # drop pre-start zeros
                is_r, oos_r = r[r.index <= IS_END], r[r.index > IS_END]
                m_is = metrics(is_r, mod.PERIODS, res.turnover)
                m_oos = metrics(oos_r, mod.PERIODS, res.turnover)
                key = f"{fam}{json.dumps(params, sort_keys=True)}"
                streams[key] = (oos_r, mod.PERIODS)
                rows.append(dict(market=mname, family=fam, params=json.dumps(params, sort_keys=True),
                                 key=key,
                                 **{f"is_{k}": v for k, v in m_is.items()},
                                 **{f"oos_{k}": v for k, v in m_oos.items()}))
    return pd.DataFrame(rows), streams


def judge(trials: pd.DataFrame, streams: dict) -> pd.DataFrame:
    n = len(trials)
    out = []
    for fam, g in trials.groupby("family", sort=False):
        best = g.loc[g["is_sharpe"].idxmax()]
        oos_r, periods = streams[best["key"]]
        dsr = deflated_sharpe(oos_r, n, 1 / len(oos_r)) if len(oos_r) > 30 and oos_r.std() > 0 else 0.0
        checks = {
            "oos_sharpe>=1": best["oos_sharpe"] >= 1.0,
            "dsr>=0.95": dsr >= 0.95,
            "beats_tbill": best["oos_cagr"] > TBILL,
            "max_dd<=25%": best["oos_max_dd"] >= -0.25,
            "is_sharpe>0": best["is_sharpe"] > 0,
            "evidence": best["oos_years"] >= 2 and best["oos_trades"] >= 30,
        }
        out.append(dict(family=fam, market=best["market"], params=best["params"],
                        is_sharpe=best["is_sharpe"], oos_sharpe=best["oos_sharpe"],
                        oos_cagr=best["oos_cagr"], oos_max_dd=best["oos_max_dd"],
                        oos_years=best["oos_years"], oos_trades=best["oos_trades"],
                        dsr=dsr, passed=all(checks.values()),
                        failed=", ".join(k for k, v in checks.items() if not v)))
    return pd.DataFrame(out)


def fmt(df: pd.DataFrame) -> str:
    d = df.copy()
    for c in d.columns:
        if c in ("oos_cagr", "oos_max_dd"):
            d[c] = d[c].map(lambda x: f"{x:+.1%}")
        elif d[c].dtype == float:
            d[c] = d[c].map(lambda x: f"{x:.2f}")
    return d.to_markdown(index=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--null-seeds", type=int, default=3)
    args = ap.parse_args()

    print("loading data...", flush=True)
    panels = {"crypto": data.crypto_panel(args.refresh), "etf": data.etf_panel(args.refresh)}
    for k, p in panels.items():
        for name, df in p.items():
            print(f"  {k}.{name}: {df.shape} {df.index.min()} -> {df.index.max()}")

    trials, streams = evaluate(panels)
    trials.drop(columns="key").to_csv(REPORTS / "trials.csv", index=False)
    verdict = judge(trials, streams)
    verdict.to_csv(REPORTS / "verdict.csv", index=False)

    bench = []
    for mname, mod in MARKETS.items():
        res = mod.benchmark(panels[mname])
        r = res.returns
        for seg, rr in (("IS", r[r.index <= IS_END]), ("OOS", r[r.index > IS_END])):
            m = metrics(rr, mod.PERIODS)
            bench.append(dict(benchmark=f"buy&hold {'BTC' if mname == 'crypto' else 'SPY'}",
                              segment=seg, sharpe=m["sharpe"], cagr=m["cagr"], max_dd=m["max_dd"]))
    bench = pd.DataFrame(bench)

    null_rows = []
    for seed in range(args.null_seeds):
        npan = {"crypto": null.crypto(panels["crypto"], seed), "etf": null.etf(panels["etf"], seed)}
        t, s = evaluate(npan)
        v = judge(t, s)
        null_rows.append(dict(seed=seed, families=len(v), passed=int(v["passed"].sum()),
                              best_oos_sharpe=float(v["oos_sharpe"].max()),
                              passers=", ".join(v.loc[v["passed"], "family"])))
    nulls = pd.DataFrame(null_rows)

    md = [
        "# Phase 1 results",
        "",
        f"Generated by `run_research.py`. Trials run: **{len(trials)}** across "
        f"**{trials['family'].nunique()}** families. In-sample ≤ {IS_END.date()}, holdout after.",
        "Rules: see [PROTOCOL.md](../PROTOCOL.md).",
        "",
        "## Verdict per family (best in-sample config, judged on holdout)",
        "",
        fmt(verdict),
        "",
        f"**Passed Phase 1: {int(verdict['passed'].sum())} / {len(verdict)}**",
        "",
        "## Benchmarks (not trials)",
        "",
        fmt(bench),
        "",
        "## Null test (same pipeline on shuffled, zero-drift data)",
        "",
        fmt(nulls),
        "",
        "If the null test shows any passers, the framework is biased and the verdict above is void.",
        "",
        "Full per-config results: [trials.csv](trials.csv).",
    ]
    (REPORTS / "RESULTS.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
